"""
training/evaluate.py
Evaluates the trained clothing classifier on the test set.
Outputs:
  - Accuracy, Precision, Recall, F1 (macro + per-class)
  - Confusion matrix
  - MODEL_EVALUATION.md

Usage:
    python training/evaluate.py
    python training/evaluate.py --data_dir datasets --model_path models/clothing_classifier.pth
"""

import os
import sys
import json
import argparse
import logging
from pathlib import Path

import torch
import numpy as np
import torchvision.datasets as datasets
from sklearn.metrics import (
    accuracy_score, precision_recall_fscore_support, confusion_matrix, classification_report
)

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

from preprocessing.image_processor import get_val_transform
from inference.predictor import ClothingPredictor

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)


def evaluate(args):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    model_path = args.model_path or str(BASE_DIR / "models" / "clothing_classifier.pth")
    label_map_path = args.label_map or str(BASE_DIR / "models" / "label_map.json")

    if not os.path.exists(model_path):
        logger.error(f"Model not found: {model_path}")
        logger.error("Train the model first: python training/train.py")
        sys.exit(1)

    logger.info(f"Loading model from {model_path}")
    predictor = ClothingPredictor(model_path=model_path, label_map_path=label_map_path)
    predictor.model.eval()

    test_dir = Path(args.data_dir) / "test"
    if not test_dir.exists():
        logger.error(f"Test directory not found: {test_dir}")
        sys.exit(1)

    test_dataset = datasets.ImageFolder(str(test_dir), transform=get_val_transform())
    test_loader = torch.utils.data.DataLoader(
        test_dataset, batch_size=64, shuffle=False, num_workers=2
    )

    class_names = test_dataset.classes
    logger.info(f"Evaluating on {len(test_dataset)} test images, {len(class_names)} classes")

    all_preds = []
    all_labels = []

    with torch.no_grad():
        for images, labels in test_loader:
            images = images.to(device)
            cat_out, _, _, _ = predictor.model(images)
            preds = cat_out.argmax(dim=1).cpu().numpy()
            all_preds.extend(preds)
            all_labels.extend(labels.numpy())

    # ── Metrics ───────────────────────────────────────────────────────────────
    acc = accuracy_score(all_labels, all_preds)
    precision, recall, f1, support = precision_recall_fscore_support(
        all_labels, all_preds, average=None, zero_division=0
    )
    macro_p, macro_r, macro_f1, _ = precision_recall_fscore_support(
        all_labels, all_preds, average="macro", zero_division=0
    )
    cm = confusion_matrix(all_labels, all_preds)

    logger.info(f"\nOverall Accuracy: {acc:.4f}")
    logger.info(f"Macro Precision:  {macro_p:.4f}")
    logger.info(f"Macro Recall:     {macro_r:.4f}")
    logger.info(f"Macro F1:         {macro_f1:.4f}")

    # ── Per-class report ──────────────────────────────────────────────────────
    logger.info("\nPer-class results:")
    for i, name in enumerate(class_names):
        logger.info(f"  {name:<20} P={precision[i]:.3f} R={recall[i]:.3f} F1={f1[i]:.3f} n={support[i]}")

    # ── Write MODEL_EVALUATION.md ─────────────────────────────────────────────
    report_dir = BASE_DIR
    report_path = str(report_dir / "MODEL_EVALUATION.md")

    lines = [
        "# MODEL EVALUATION REPORT",
        "",
        "Generated by `training/evaluate.py`",
        "",
        "## Overall Metrics",
        "",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| Test images | {len(test_dataset)} |",
        f"| Number of classes | {len(class_names)} |",
        f"| Overall Accuracy | {acc:.4f} ({acc*100:.1f}%) |",
        f"| Macro Precision | {macro_p:.4f} |",
        f"| Macro Recall | {macro_r:.4f} |",
        f"| Macro F1 | {macro_f1:.4f} |",
        "",
        "## Per-Class Performance",
        "",
        "| Class | Precision | Recall | F1 | Support |",
        "|-------|-----------|--------|----|---------|",
    ]

    for i, name in enumerate(class_names):
        flag = " ⚠️" if f1[i] < 0.5 else ""
        lines.append(f"| {name}{flag} | {precision[i]:.3f} | {recall[i]:.3f} | {f1[i]:.3f} | {support[i]} |")

    # Highlight poor performers
    poor = [(class_names[i], f1[i]) for i in range(len(class_names)) if f1[i] < 0.5]
    if poor:
        lines += [
            "",
            "## ⚠️ Poor-Performing Classes",
            "",
            "The following classes have F1 < 0.5 and may need more training data or review:",
            "",
        ]
        for name, score in sorted(poor, key=lambda x: x[1]):
            lines.append(f"- **{name}** — F1: {score:.3f}")

    # Good performers
    good = [(class_names[i], f1[i]) for i in range(len(class_names)) if f1[i] >= 0.80]
    if good:
        lines += [
            "",
            "## ✅ Strong-Performing Classes",
            "",
            "The following classes have F1 ≥ 0.8:",
            "",
        ]
        for name, score in sorted(good, key=lambda x: -x[1]):
            lines.append(f"- **{name}** — F1: {score:.3f}")

    lines += [
        "",
        "## Confusion Matrix",
        "",
        f"Rows = actual class, Columns = predicted class",
        f"Classes: {', '.join(class_names)}",
        "",
        "```",
    ]
    for row in cm:
        lines.append("  " + "  ".join(f"{v:5}" for v in row))
    lines += ["```", ""]

    with open(report_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    logger.info(f"Evaluation report saved: {report_path}")


def main():
    parser = argparse.ArgumentParser(description="Evaluate trained clothing classifier")
    parser.add_argument("--data_dir",    default="datasets",              help="Directory with test split")
    parser.add_argument("--model_path",  default=None,                    help="Path to .pth checkpoint")
    parser.add_argument("--label_map",   default=None,                    help="Path to label_map.json")
    args = parser.parse_args()
    evaluate(args)


if __name__ == "__main__":
    main()
